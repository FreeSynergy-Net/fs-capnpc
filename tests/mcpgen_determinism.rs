//! The output depends on the request only: twice = equal, the nodes in another order = equal, no time, no absolute path.

#[path = "cligen_common/mod.rs"]
mod common;

use capnp::message::{Builder, ReaderOptions};
use capnp::schema_capnp::code_generator_request;

fn generate(bytes: &[u8]) -> String {
    let files = capnp_compiler::mcpgen::GenerationCommand::new()
        .generate(bytes)
        .unwrap();
    files.into_iter().map(|f| f.content).collect()
}

/// The request with its nodes in reverse order.
fn reversed(bytes: &[u8]) -> Vec<u8> {
    let msg = capnp::serialize::read_message(&mut &bytes[..], ReaderOptions::new()).unwrap();
    let req: code_generator_request::Reader<'_> = msg.get_root().unwrap();
    let mut out = Builder::new_default();
    out.set_root(req).unwrap();
    let nodes = req.get_nodes().unwrap();
    let n = nodes.len();
    let mut b = out
        .get_root::<code_generator_request::Builder<'_>>()
        .unwrap();
    let mut list = b.reborrow().init_nodes(n);
    for i in 0..n {
        list.set_with_caveats(n - 1 - i, nodes.get(i)).unwrap();
    }
    capnp::serialize::write_message_to_words(&out)
}

#[test]
fn twice_and_reordered_are_byte_equal() {
    let sets: Vec<Vec<u8>> = [
        &["tasks.capnp"][..],
        &["features.capnp", "capnpc_cli.capnp"],
        &["mcp.capnp", "capnpc_cli.capnp"],
        &["multi.capnp", "common.capnp"],
    ]
    .iter()
    .map(|s| common::request(s))
    .collect();
    for bytes in &sets {
        let (a, r) = (generate(bytes), reversed(bytes));
        // hash seeds differ from map to map, so one run can pass by luck; ten runs cannot
        for round in 0..10 {
            assert_eq!(a, generate(bytes), "run {round}");
            assert_eq!(a, generate(&r), "reordered, run {round}");
        }
    }
}

#[test]
fn head_has_no_time_and_no_path() {
    let text = generate(&common::request(&["tasks.capnp"]));
    let head = text.lines().next().unwrap();
    assert!(head.starts_with("// @generated by capnpc-mcp 0."), "{head}");
    assert!(
        head.contains(&format!("mcp ABI {}", capnp_compiler::mcpgen::rt::ABI))
            && head.contains("MCP revision 2026-07-28")
            && head.contains("from tasks.capnp"),
        "{head}"
    );
    assert!(!text.contains("/srv/") && !text.contains(env!("CARGO_MANIFEST_DIR")));
}

#[test]
fn name_with_a_folder_keeps_the_slash() {
    let files = capnp_compiler::mcpgen::GenerationCommand::new()
        .generate(&common::request(&["sub/nested.capnp"]))
        .unwrap();
    assert_eq!(files[0].name, "nested_mcp.rs");
    let head = files[0].content.lines().next().unwrap();
    assert!(
        head.contains("from sub/nested.capnp;") && !head.contains('\\'),
        "{head}"
    );
}
