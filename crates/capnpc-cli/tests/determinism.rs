//! T8: the output depends on the request only. Twice = equal; the nodes in another order = equal; no time, no
//! absolute path, no backslash.

mod common;

use capnp::message::{Builder, ReaderOptions};
use capnp::schema_capnp::code_generator_request;

fn generate(bytes: &[u8]) -> String {
    let files = capnpc_cli::GenerationCommand::new()
        .generate(bytes)
        .unwrap();
    files.into_iter().map(|f| f.content).collect()
}

/// The request with its nodes in reverse order.
fn reversed(bytes: &[u8]) -> Vec<u8> {
    let msg = capnp::serialize::read_message(&mut &bytes[..], ReaderOptions::new()).unwrap();
    let req: code_generator_request::Reader<'_> = msg.get_root().unwrap();
    let mut out = Builder::new_default();
    out.set_root(req).unwrap();
    let nodes = req.get_nodes().unwrap();
    let n = nodes.len();
    let mut b = out
        .get_root::<code_generator_request::Builder<'_>>()
        .unwrap();
    let mut list = b.reborrow().init_nodes(n);
    for i in 0..n {
        list.set_with_caveats(n - 1 - i, nodes.get(i)).unwrap();
    }
    capnp::serialize::write_message_to_words(&out)
}

#[test]
fn t8_twice_and_reordered_are_byte_equal() {
    let bytes = common::request(&["tasks.capnp"]);
    let f = common::request(&["features.capnp", "capnpc_cli.capnp"]);
    let (rb, rf) = (reversed(&bytes), reversed(&f));
    let a = generate(&bytes);
    let fa = generate(&f);
    // [TEST-MEHRFACH]: hash seeds differ from map to map, so one run can pass by luck; ten runs cannot
    for round in 0..10 {
        assert_eq!(a, generate(&bytes), "tasks, run {round}");
        assert_eq!(a, generate(&rb), "tasks reordered, run {round}");
        assert_eq!(fa, generate(&f), "features, run {round}");
        assert_eq!(fa, generate(&rf), "features reordered, run {round}");
    }
}

#[test]
fn t8_head_has_no_time_and_no_path() {
    let text = generate(&common::request(&["tasks.capnp"]));
    let head = text.lines().next().unwrap();
    assert!(head.starts_with("// @generated by capnpc-cli 0."), "{head}");
    assert!(
        head.contains("rt ABI 1") && head.contains("from tasks.capnp"),
        "{head}"
    );
    assert!(!head.contains('\\'));
    assert!(!text.contains("/srv/") && !text.contains(env!("CARGO_MANIFEST_DIR")));
}
